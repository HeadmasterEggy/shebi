# -*- coding: utf-8 -*-
"""方面词典与极性词典。

两份确定性的词表，被三处共用：extract_aspects 工具、Critic 的引用校验、
标定脚本。用词典而不是让 LLM 抽方面，理由是可复算——同一批评论跑一百次
得到同一个统计口径，换个模型不会突然冒出一个"综合体验"把分类搅乱。

词典的短板也要说清楚：它只认字面，"一天要充三次电"命中不了「续航」。
所以方面统计用词典，语义召回用向量（vectorstore），两者分工不同。
"""

from __future__ import annotations

from typing import Dict, List, Optional, Set

ASPECT_LEXICON: Dict[str, List[str]] = {
    "物流配送": ["物流", "快递", "发货", "送货", "配送", "到货", "运输", "签收", "顺丰", "京东快递"],
    "包装": ["包装", "盒子", "外包装", "箱子", "封装", "膜"],
    "质量做工": ["质量", "做工", "工艺", "材质", "用料", "结实", "牢固", "劣质", "瑕疵", "破损", "坏了"],
    "客服服务": ["客服", "态度", "服务", "回复", "售前", "咨询"],
    "价格": ["价格", "便宜", "贵", "性价比", "划算", "优惠", "降价", "值"],
    "外观": ["外观", "颜值", "好看", "漂亮", "设计", "颜色", "手感", "轻薄"],
    "性能": ["性能", "速度", "流畅", "卡顿", "配置", "反应", "运行", "死机"],
    "续航": ["续航", "电池", "充电", "耗电", "待机", "电量"],
    "屏幕": ["屏幕", "显示", "分辨率", "色彩", "亮度", "划痕"],
    "售后": ["售后", "退货", "退款", "换货", "保修", "维修", "退换"],
}

# 结论里断言"这是负面/正面"的措辞。用于 Critic 的极性一致校验。
NEGATIVE_MARKERS = [
    "差评", "负面", "消极", "不满", "抱怨", "吐槽", "投诉", "诟病", "问题",
    "不好", "不行", "糟糕", "失望", "太差", "很差", "偏差", "缺点", "槽点",
    "慢", "破损", "损坏", "劣质", "退货", "退款", "卡顿", "故障",
]
POSITIVE_MARKERS = [
    "好评", "正面", "积极", "满意", "称赞", "夸", "推荐", "优点", "亮点",
    "不错", "很好", "出色", "优秀", "惊喜", "值得", "流畅", "快",
]


def aspects_of(text: str) -> Set[str]:
    """文本命中了哪些方面。"""
    return {aspect for aspect, words in ASPECT_LEXICON.items()
            if any(w in text for w in words)}


def asserted_polarity(claim: str) -> Optional[str]:
    """这条结论断言的是好评还是差评；两者都提或都不提则返回 None。

    返回 None 不是失败——「物流配送被提及 37 次」这类纯计数结论本来就
    不断言极性，对它做极性校验反而会误伤。
    """
    neg = any(m in claim for m in NEGATIVE_MARKERS)
    pos = any(m in claim for m in POSITIVE_MARKERS)
    if neg == pos:
        return None
    return "消极" if neg else "积极"
